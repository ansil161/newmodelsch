"""A small golden dataset for retrieval and answer evaluation.

Deliberately small and hand-written. The point of a golden set is not
coverage — it is that a human decided what the right answer is, so a
regression is unambiguous. Twelve questions someone has actually checked are
worth more than a thousand generated by a model, which only measure agreement
with whatever generated them.

The corpus is representative of the shapes a real knowledge base contains,
because each shape breaks a different retriever:

  * prose policy text            — dense retrieval handles this well
  * part numbers and SKUs        — dense retrieval is nearly blind to these,
                                   which is why sparse exists
  * numeric specifications       — exact figures a model loves to round
  * near-duplicate passages      — tests deduplication in context building
  * a distractor document        — similar vocabulary, wrong answer

`unanswerable` questions are as important as answerable ones. A RAG system
that never says "I don't know" is not accurate, it is confident, and the
difference only shows up if the dataset contains questions the corpus cannot
answer.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Document:
    id: str
    name: str
    doc_type: str
    chunks: list[str]


@dataclass(frozen=True)
class Case:
    question: str
    # Documents that genuinely contain the answer. Retrieval metrics are
    # computed against these.
    relevant_documents: set[str]
    # Strings that must appear in a correct answer. Kept short and factual —
    # a number, a name — so the check is about groundedness, not phrasing.
    expected_facts: list[str] = field(default_factory=list)
    # True when the corpus cannot answer it. The system should say so.
    unanswerable: bool = False
    # What this case is probing, for the report.
    probes: str = ""


